// Rebuild src/seam.js from the us-atlas 10m states.
//
//   node script/build-seam.mjs

import {mkdirSync, readFileSync, writeFileSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
import {mesh, merge} from "topojson-client";
import {geoCentroid, geoAlbers} from "d3-geo";
import polygonClipping from "polygon-clipping";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const atlasPath = join(root, "data/states-10m.json");
const outPath = join(root, "src/seam.js");

const eastIds = new Set("01 05 09 10 11 12 13 17 18 19 21 22 23 24 25 26 27 28 29 33 34 36 37 39 42 44 45 47 50 51 54 55".split(" "));
const westIds = new Set("04 06 08 16 20 30 31 32 35 38 40 41 46 48 49 53 56".split(" "));

mkdirSync(join(root, "data"), {recursive: true});
try {
  readFileSync(atlasPath);
} catch {
  const response = await fetch("https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-10m.json");
  if (!response.ok) throw new Error(`Could not download states-10m.json (${response.status})`);
  writeFileSync(atlasPath, Buffer.from(await response.arrayBuffer()));
}

const topology = JSON.parse(readFileSync(atlasPath, "utf8"));
const states = topology.objects.states;
const seam = stitch(mesh(topology, states, (a, b) => {
  if (!a || !b || a === b) return false;
  const aEast = eastIds.has(a.id), bEast = eastIds.has(b.id);
  const aWest = westIds.has(a.id), bWest = westIds.has(b.id);
  return (aEast && bWest) || (aWest && bEast);
}).coordinates);
if (seam[0][1] < seam[seam.length - 1][1]) seam.reverse();

function land(ids) {
  return merge(topology, states.geometries.filter(d => ids.has(d.id)));
}

const eastLand = land(eastIds);
const westLand = land(westIds);
const eastBox = geoBox(eastLand);
const westBox = geoBox(westLand);
const pad = 0.4;
const frame = [
  round(westBox[0] - pad),
  round(Math.min(eastBox[1], westBox[1]) - pad),
  round(eastBox[2] + pad),
  round(Math.max(eastBox[3], westBox[3]) + pad)
];
const [, south, , north] = frame;
const roundedSeam = dedupe(seam.map(([lon, lat]) => [round(lon), round(lat)]));
const eastRing = orient(roundedSeam.concat([
  [roundedSeam[roundedSeam.length - 1][0], south],
  [frame[2], south],
  [frame[2], north],
  [roundedSeam[0][0], north]
]));
const westRing = orient(roundedSeam.concat([
  [roundedSeam[roundedSeam.length - 1][0], south],
  [frame[0], south],
  [frame[0], north],
  [roundedSeam[0][0], north]
]));

for (const geometry of states.geometries) {
  if (!eastIds.has(geometry.id) && !westIds.has(geometry.id)) continue;
  const centroid = geoCentroid(merge(topology, [geometry]));
  const inEast = contains(eastRing, centroid[0], centroid[1]);
  const inWest = contains(westRing, centroid[0], centroid[1]);
  const wantEast = eastIds.has(geometry.id);
  if (wantEast ? !(inEast && !inWest) : !(inWest && !inEast)) {
    throw new Error(`${geometry.properties.name} centroid ${centroid} is east=${inEast} west=${inWest}`);
  }
}

const eastClip = [[close(eastRing)]];
const westClip = [[close(westRing)]];
for (const geometry of states.geometries) {
  if (!eastIds.has(geometry.id) && !westIds.has(geometry.id)) continue;
  const shape = merge(topology, [geometry]).coordinates;
  const wantEast = eastIds.has(geometry.id);
  const stray = polygonClipping.intersection(shape, wantEast ? westClip : eastClip);
  const strayArea = stray.reduce((sum, polygon) => sum + polygon.reduce((part, ring) => part + Math.abs(ringArea(ring)), 0), 0);
  if (strayArea > 1e-4) throw new Error(`${geometry.properties.name} leaves ${strayArea} on the other side of the seam`);
}

const eastExtent = extremes(geoAlbers().scale(1).translate([0, 0]), eastLand);
const westExtent = extremes(geoAlbers().scale(1).translate([0, 0]), westLand);

writeFileSync(outPath, `// Generated by script/build-seam.mjs from us-atlas 3.0.1 states-10m.
// Do not edit. The seam runs north to south along the western borders of
// Minnesota, Iowa, Missouri, Arkansas, and Louisiana. Each ring closes that
// border around the states on one side, including a margin of ocean.

export const frame = ${JSON.stringify(frame)};

export const eastExtent = ${JSON.stringify(eastExtent)};

export const westExtent = ${JSON.stringify(westExtent)};

export const eastRing = ${formatRing(eastRing)};

export const westRing = ${formatRing(westRing)};
`);

console.log(`wrote ${outPath} (${eastRing.length} east vertices, ${westRing.length} west vertices)`);

function stitch(lines) {
  const unused = lines.map(line => line.slice());
  const parts = [];
  const same = (p, q) => Math.hypot(p[0] - q[0], p[1] - q[1]) < 1e-8;
  while (unused.length) {
    let line = unused.pop();
    let grew = true;
    while (grew) {
      grew = false;
      for (let i = 0; i < unused.length; ++i) {
        const other = unused[i];
        const a = line[0], b = line[line.length - 1], c = other[0], d = other[other.length - 1];
        if (same(b, c)) line = line.concat(other.slice(1));
        else if (same(b, d)) line = line.concat(other.slice(0, -1).reverse());
        else if (same(a, d)) line = other.concat(line.slice(1));
        else if (same(a, c)) line = other.slice().reverse().concat(line.slice(1));
        else continue;
        unused.splice(i, 1);
        grew = true;
        break;
      }
    }
    parts.push(line);
  }
  if (parts.length !== 1) throw new Error(`expected one seam, found ${parts.length}`);
  return parts[0];
}

function geoBox(geometry) {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const polygon of geometry.coordinates) {
    for (const [x, y] of polygon[0]) {
      if (x < x0) x0 = x;
      if (y < y0) y0 = y;
      if (x > x1) x1 = x;
      if (y > y1) y1 = y;
    }
  }
  return [x0, y0, x1, y1];
}

function extremes(projection, geometry) {
  let minX, maxX, minY, maxY;
  for (const polygon of geometry.coordinates) {
    for (const ll of polygon[0]) {
      const p = projection(ll);
      if (!minX || p[0] < minX[0]) minX = [p[0], ll];
      if (!maxX || p[0] > maxX[0]) maxX = [p[0], ll];
      if (!minY || p[1] < minY[0]) minY = [p[1], ll];
      if (!maxY || p[1] > maxY[0]) maxY = [p[1], ll];
    }
  }
  return [minX[1], maxX[1], minY[1], maxY[1]].map(([lon, lat]) => [round(lon), round(lat)]);
}

function dedupe(ring) {
  const out = [];
  for (const p of ring) {
    const prev = out[out.length - 1];
    if (prev && prev[0] === p[0] && prev[1] === p[1]) continue;
    out.push(p);
  }
  return out;
}

function orient(ring) {
  return ringArea(ring) < 0 ? ring.slice().reverse() : ring;
}

function ringArea(ring) {
  let area = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    area += ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
  }
  return area / 2;
}

function close(ring) {
  const first = ring[0], last = ring[ring.length - 1];
  return first[0] === last[0] && first[1] === last[1] ? ring : ring.concat([first]);
}

function contains(ring, x, y) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0], yi = ring[i][1];
    const xj = ring[j][0], yj = ring[j][1];
    const dx = xj - xi, dy = yj - yi;
    const l2 = dx * dx + dy * dy;
    if (l2 > 0) {
      let t = ((x - xi) * dx + (y - yi) * dy) / l2;
      if (t < 0) t = 0;
      else if (t > 1) t = 1;
      const px = xi + t * dx, py = yi + t * dy;
      if ((px - x) ** 2 + (py - y) ** 2 < 1e-12) return true;
    }
    if (((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi)) inside = !inside;
  }
  return inside;
}

function round(n) {
  return Math.round(n * 1e5) / 1e5;
}

function formatRing(ring) {
  return `[\n${ring.map(([lon, lat]) => `  [${lon}, ${lat}]`).join(",\n")}\n]`;
}
